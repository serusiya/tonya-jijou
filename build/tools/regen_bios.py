STATS=['commerce_skill','integrity_loyalty','greed_index','audacity_courage','diplomacy_charm','betrayal_risk']
RMAP={'商業競爭對手（同業批發商）':'rival','大番頭候選（經營總管）':'manager','港務與稅務奉行（腐敗官員）':'official','遠洋海運走私首領（私梟黑市）':'smuggler','用心棒保鑣總頭目（忠勇侍衛）':'guard','情報販子與掮客（眼線密探）':'broker','地方商號座客散戶':'guest','吉原花魁名伶（紅顏知己）':'oiran'}
def role_class(c):
    rs={RMAP.get(r) for r in c['suitable_roles']}
    if len(rs)==1:return rs.pop()
    return 'oiran-mixed' if 'oiran' in rs else 'mixed'
def top_stat(c):
    s=c['derived_stats']
    if s['betrayal_risk']>=52:return 'betrayal_risk'
    return max(STATS[:5],key=lambda k:s[k])
def pron(c):return '她' if c['gender']=='女' else '他'

