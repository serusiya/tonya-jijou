/** 取按鈕／選項文字，並代入 {變數}。 */
function UT(key,vars){
  let v=UI_TXT[key];if(v===undefined)return key;
  return vars?v.replace(/\{(\w+)\}/g,(m,k)=>vars[k]===undefined?m:vars[k]):v;
}
