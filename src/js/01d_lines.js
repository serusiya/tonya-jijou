const _lineAt=path=>path.split('.').reduce((o,k)=>o&&o[k],LINES);
/** 取一句台詞（陣列則隨機挑一句），並代入 {佔位}。 */
function TX(path,vars){
  let v=_lineAt(path);if(v===undefined)return '';
  if(Array.isArray(v))v=v[Math.floor(rnd()*v.length)];
  return vars?String(v).replace(/\{(\w+)\}/g,(m,k)=>vars[k]===undefined?m:vars[k]):v;
}
